/* ============================ progress (localStorage) ============================ */
const PROG_KEY = "bw-tour-progress-v1";
function loadProgress(key) {
  try {
    const p = JSON.parse(localStorage.getItem(key || PROG_KEY));
    return { visited: Array.isArray(p.visited) ? p.visited : [], last: p.last || null };
  } catch (e) { return { visited: [], last: null }; }
}
function saveProgress(prog, key) {
  try { localStorage.setItem(key || PROG_KEY, JSON.stringify(prog)); } catch (e) { /* private mode */ }
}
const prog = loadProgress();
function markVisited(id) {
  if (!prog.visited.includes(id)) prog.visited.push(id);
  prog.last = id;
  saveProgress(prog);
  paintStepper();
}

