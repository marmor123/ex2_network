/* ============================ symbol → owner station ============================ */
/* A cross-link symbol resolves to the station that owns its first
   occurrence in the source — but only as a real token, not a comment
   mention (`main` appears in the license's prose; the code token is the
   definition). Comment-only symbols (bw_template.c) fall back to a
   word-boundary text search. */
function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
function symbolOwner(sym) {
  for (let l = 0; l < TOK_LINES.length; l++) {
    for (const t of TOK_LINES[l].toks) {
      if (t.t !== "com" && t.s === sym) {
        const own = STATION_OF_LINE.get(l + 1);
        if (own) return own;
      }
    }
  }
  const re = new RegExp("\\b" + escapeRe(sym) + "\\b");
  for (let l = 0; l < LINE_TEXT.length; l++) {
    if (re.test(LINE_TEXT[l])) {
      const own = STATION_OF_LINE.get(l + 1);
      if (own) return own;
    }
  }
  return null;
}
const SYMBOL_OWNER = new Map();
function resolveSymbol(sym) {
  if (!SYMBOL_OWNER.has(sym)) SYMBOL_OWNER.set(sym, symbolOwner(sym));
  return SYMBOL_OWNER.get(sym);
}

/* ============================ self-check ============================ */
/* The content parse self-check: verifies the renderer contract over the
   embedded content at load. Hard failures show a red banner; soft ones
   are warnings. ?selftest=1 additionally exercises the DOM. */
const checks = [];
function report(name, pass, detail, warn) {
  checks.push({ name, pass, warn: !!warn, detail });
}
function checkLineCoverage() {
  const ownerCount = new Map();
  const last = SRC_LINES.length;
  let inBounds = true;
  for (const st of STATIONS) {
    if (!Array.isArray(st.range)) continue;
    if (st.range[0] < 1 || st.range[1] > last || st.range[0] > st.range[1]) inBounds = false;
    for (let l = st.range[0]; l <= st.range[1]; l++)
      ownerCount.set(l, (ownerCount.get(l) || 0) + 1);
  }
  let exact = inBounds;
  for (let l = 1; l <= last; l++) if (ownerCount.get(l) !== 1) { exact = false; break; }
  return { exact, inBounds, sum: [...ownerCount.values()].reduce((a, b) => a + b, 0) };
}
function runChecks() {
  /* content shape */
  report("content.stations", STATION_SRCS.length === 53,
    STATION_SRCS.length + " station files embedded (52 + capstone)");
  report("content.source-lines", SRC_LINES.length === 1320,
    SRC_LINES.length + " source lines (pinned bw.c has 1320)");
  report("content.unique-ids", new Set(STATION_IDS).size === STATION_IDS.length,
    STATION_IDS.length + " stations, " + (STATION_IDS.length - new Set(STATION_IDS).size) + " duplicate ids");
  report("content.capstone", STATION_BY_ID.has("capstone") && STATION_BY_ID.get("capstone").type === "content",
    "the capstone is the content station");

  /* tokenizer: the tokenizer splits per line (newlines live between lines),
     so zero loss means lines joined with "\n" reproduce the source. */
  let rebuild = TOK_LINES.map(ln => ln.text).join("\n");
  const ok = rebuild === SRC_LINES.join("\n");
  report("tokenizer.roundtrip", ok, ok ? "token text reproduces the source exactly (zero loss)"
    : "token text differs from the source (" + Math.abs(rebuild.length - SRC.length) + " chars off)");

  /* headers */
  let badType = 0, badTag = 0, badRange = 0, badSkip = 0, badTitle = 0;
  for (const st of STATIONS) {
    if (!st.title) badTitle++;
    if (!STATION_TYPES.has(st.type)) badType++;
    if (!st.tags.length || st.tags.some(t => !CANONICAL_TAGS.has(t))) badTag++;
    if (typeof st.range === "string") badRange++;
    if (st.skipRaw !== "yes" && st.skipRaw !== "no") badSkip++;
  }
  report("headers.title", badTitle === 0, badTitle ? badTitle + " stations lack a title" : "all stations titled");
  report("headers.type", badType === 0, badType ? badType + " bad types" : "types in {file, constant, struct, function, content}");
  report("headers.tags", badTag === 0, badTag ? badTag + " stations with non-canonical tags" : "tags within the canonical nine");
  report("headers.lines", badRange === 0, badRange ? badRange + " unparseable line ranges" : "line ranges parse");
  report("headers.skip", badSkip === 0, badSkip ? badSkip + " bad skip values" : "skip values are yes/no");

  /* the partition: every line owned exactly once, ranges inside the file,
     capstone owns none */
  const cov = checkLineCoverage();
  report("partition.exact", cov.exact,
    cov.inBounds && cov.sum === 1320
      ? "lines 1–1320 owned exactly once (sum " + cov.sum + ")"
      : "ownership not exact (sum " + cov.sum + ", ranges in bounds: " + cov.inBounds + ")");
  const noRange = STATIONS.filter(s => !Array.isArray(s.range));
  report("partition.none-lines", noRange.length === 1 && noRange[0].id === "capstone",
    noRange.length === 1 ? "only the capstone owns no lines" : noRange.length + " stations own no lines");

  /* blocks */
  let predictCount = 0, brokenPredicts = 0, fenceCount = 0, tableBad = 0, diagramBad = 0;
  for (const st of STATIONS) {
    for (const b of st.blocks) {
      if (b.k === "predict") {
        predictCount++;
        if (b.broken || !b.q || !b.a) brokenPredicts++;
      } else if (b.k === "unknown") {
        fenceCount++; // an unclosed fence is an unknown block
      } else if (b.k === "table") {
        fenceCount++;
        const cols = b.rows[0] ? b.rows[0].length : 0;
        if (!cols || b.rows.length < 2) tableBad++;
        else for (const r of b.rows) if (r.length !== cols) { tableBad++; break; }
      } else if (b.k === "diagram") {
        fenceCount++;
        if (!b.closed || !/^<svg[\s>]/.test(b.html) || !/<\/svg>/.test(b.html) ||
            !/<figcaption[\s>]/.test(b.html) || !/<\/figcaption>/.test(b.html)) diagramBad++;
      }
    }
  }
  report("blocks.predicts", predictCount === 10 && brokenPredicts === 0,
    predictCount + " predict/reveal pairs, " + brokenPredicts + " broken (partition §5 lists 10)");
  report("blocks.fences", fenceCount === 15 && tableBad === 0 && diagramBad === 0,
    fenceCount + " extension blocks (" + (fenceCount - tableBad - diagramBad) + " well-formed, " +
    tableBad + " bad tables, " + diagramBad + " bad diagrams)");
  const noBlocks = STATIONS.filter(s => !s.blocks.length);
  report("blocks.present", noBlocks.length === 0,
    noBlocks.length ? noBlocks.map(s => s.id).join(", ") + " have no body" : "every station has body blocks");

  /* cross-links */
  let refs = 0, unresolved = [];
  for (const st of STATIONS) {
    for (const b of st.blocks) {
      if (b.k !== "xlink") continue;
      for (const sym of b.refs) {
        refs++;
        if (resolveSymbol(sym) === null) unresolved.push(st.id + ":" + sym);
      }
    }
  }
  report("xlink.resolves", unresolved.length === 0,
    refs + " cross-links, " + unresolved.length + " unresolvable" +
    (unresolved.length ? " — " + unresolved.slice(0, 5).join(", ") : ""), unresolved.length > 0);
  const noXlink = STATIONS.filter(s => s.id !== "capstone" && !s.blocks.some(b => b.k === "xlink"));
  report("xlink.present", noXlink.length === 0,
    noXlink.length ? noXlink.map(s => s.id).join(", ") + " lack cross-links" : "every station has cross-links", noXlink.length > 0);

  /* route */
  const routeIds = ROUTE.map(r => r.id);
  const dupes = routeIds.filter((id, i) => routeIds.indexOf(id) !== i);
  const missing = STATION_IDS.filter(id => !ROUTE_POS.has(id));
  report("route.covers", dupes.length === 0 && missing.length === 0,
    routeIds.length + " route stops; " + dupes.length + " duplicates; " + missing.length + " stations not routed");
}

