/* ============================ tokenizer ============================ */
/* Hand-rolled C tokenizer (the prototype's proven algorithm, rewritten):
   one {toks, text} record per line; block comments span lines. The
   self-check verifies zero loss (concatenating token text reproduces the
   source exactly). */
const KW = new Set(("auto break case char const continue default do double else enum extern " +
  "float for goto if inline int long register restrict return short signed sizeof static " +
  "struct switch typedef union unsigned void volatile while").split(" "));
const TYPES = new Set(("uint32_t uint64_t uint8_t uint16_t int8_t int16_t int32_t int64_t " +
  "size_t ssize_t bool FILE ibv_context ibv_pd ibv_mr ibv_cq ibv_qp ibv_wc ibv_send_wr ibv_sge " +
  "ibv_gid ibv_port_attr ibv_device ibv_qp_type ibv_wr ibv_mtu ibv_wc_status ibv_qp_state " +
  "struct timespec timeval socklen_t").split(" "));
const TWO_OPS = new Set(["->", "<<", ">>", "<=", ">=", "==", "!=", "&&", "||", "++", "--"]);
const NUM_CHARS = new Set("0123456789abcdefABCDEFxXoObBuUlL.".split(""));
const WORD_START = /[A-Za-z_]/;
const WORD_REST = /[A-Za-z0-9_]/;

function tokenize(src) {
  const lines = [];
  let i = 0, n = src.length, inBlock = false;
  let toks = [], text = "";
  const flush = () => { lines.push({ toks, text }); toks = []; text = ""; };
  while (i < n) {
    const c = src[i];
    if (c === "\n") { flush(); i++; continue; }
    if (inBlock) {
      if (c === "*" && src[i + 1] === "/") {
        toks.push({ t: "com", s: "*/" }); text += "*/"; i += 2; inBlock = false;
      } else { toks.push({ t: "com", s: c }); text += c; i++; }
      continue;
    }
    if (c === "/" && src[i + 1] === "/") {           // line comment
      let j = i; while (j < n && src[j] !== "\n") j++;
      const s = src.slice(i, j); toks.push({ t: "com", s }); text += s; i = j; continue;
    }
    if (c === "/" && src[i + 1] === "*") {           // block comment
      toks.push({ t: "com", s: "/*" }); text += "/*"; i += 2; inBlock = true; continue;
    }
    if (c === '"' || c === "'") {                    // string / char literal
      let j = i + 1, s = c;
      while (j < n) {
        const d = src[j]; s += d; j++;
        if (d === "\\" && j < n) { s += src[j]; j++; continue; }
        if (d === c) break;
      }
      toks.push({ t: "str", s }); text += s; i = j; continue;
    }
    if (c === "#") {                                 // preprocessor line
      let j = i; while (j < n && src[j] !== "\n") j++;
      const s = src.slice(i, j); toks.push({ t: "pp", s }); text += s; i = j; continue;
    }
    if (NUM_CHARS.has(c)) {                          // number literal
      let j = i;
      while (j < n && NUM_CHARS.has(src[j])) j++;
      const s = src.slice(i, j); toks.push({ t: "num", s }); text += s; i = j; continue;
    }
    if (WORD_START.test(c)) {                        // identifier
      let j = i;
      while (j < n && WORD_REST.test(src[j])) j++;
      const w = src.slice(i, j);
      toks.push({ t: KW.has(w) ? "kw" : TYPES.has(w) ? "type" : "id", s: w });
      text += w; i = j; continue;
    }
    const two = src.slice(i, i + 2);
    if (TWO_OPS.has(two)) { toks.push({ t: "id", s: two }); text += two; i += 2; continue; }
    toks.push({ t: "id", s: c }); text += c; i++;
  }
  if (toks.length) flush();   // no trailing empty line when the source ends with "\n"
  return lines;
}
const TOK_LINES = tokenize(SRC);
const LINE_TEXT = TOK_LINES.map(ln => ln.text);

/* ============================ station parser ============================ */
/* Parses the markdown-ish station format (docs/tour/stations/README.md):
   `# title`, `- type/tags/lines/skip` front matter, then body blocks —
   paragraphs (**What./How./Why.**), `> ⚠` watch-outs, `> **Predict**` /
   `> **Reveal**` pairs, `**Cross-links:**`, and the `:::table` / `:::diagram`
   extension blocks. */
function stationIdFromFile(file) {
  return file === "capstone.md" ? "capstone" : file.slice(0, 2);
}

function parseStation(file, text) {
  const lines = splitLines(text);
  const title = lines[0].replace(/^#\s*/, "").trim();
  const fm = { type: null, tags: [], range: null, skip: false, skipRaw: "no" };
  let i = 1;
  for (; i < lines.length; i++) {
    const ln = lines[i];
    if (ln.trim() === "") continue;          // blank line between title and matter
    const m = /^-\s*([A-Za-z]+)\s*:\s*(.*)$/.exec(ln);
    if (!m) break;
    const [, key, val] = m;
    const v = val.trim();
    if (key === "type") fm.type = v;
    else if (key === "tags") fm.tags = v.split(",").map(s => s.trim()).filter(Boolean);
    else if (key === "lines") {
      if (v === "none") fm.range = null;
      else {
        const mm = /^(\d+)-(\d+)$/.exec(v);
        if (mm) fm.range = [parseInt(mm[1], 10), parseInt(mm[2], 10)];
        else fm.range = "bad:" + v;   // flagged by the self-check
      }
    } else if (key === "skip") { fm.skipRaw = v; fm.skip = v === "yes"; }
  }
  return {
    id: stationIdFromFile(file),
    file,
    title,
    type: fm.type,
    tags: fm.tags,
    range: fm.range,
    skip: fm.skip,
    skipRaw: fm.skipRaw,
    blocks: parseBlocks(lines.slice(i))
  };
}

function parseBlocks(lines) {
  const blocks = [];
  let i = 0;
  while (i < lines.length) {
    const ln = lines[i];
    if (ln.trim() === "") { i++; continue; }
    if (ln.trim().startsWith(":::")) {                 // extension block
      const opener = ln.trim().slice(3);
      const content = [];
      i++;
      let closed = false;
      while (i < lines.length && lines[i].trim() !== ":::") {
        content.push(lines[i]); i++;
      }
      if (i < lines.length) { closed = true; i++; }
      blocks.push(extensionBlock(opener, content, closed));
      continue;
    }
    const chunk = [ln]; i++;                            // paragraph / quote chunk
    while (i < lines.length && lines[i].trim() !== "" &&
           !lines[i].trim().startsWith(":::")) { chunk.push(lines[i]); i++; }
    blocks.push(textBlock(chunk));
  }
  return blocks;
}

function extensionBlock(opener, content, closed) {
  if (opener === "table") return { k: "table", rows: parseTable(content) };
  if (opener === "diagram")
    return { k: "diagram", html: content.join("\n").trim(), closed };
  return { k: "unknown", opener, closed };
}

function parseTable(lines) {
  const rows = [];
  for (const ln of lines) {
    if (!ln.trim()) continue;
    const cells = ln.split("|").map(c => c.trim());
    if (cells.length >= 2 && cells[0] === "") cells.shift();
    if (cells.length && cells[cells.length - 1] === "") cells.pop();
    rows.push(cells);
  }
  // Drop a `|---|---|` separator row right after the header.
  if (rows.length >= 2 && rows[1].every(c => /^:?-+:?$/.test(c))) rows.splice(1, 1);
  return rows;
}

function textBlock(chunk) {
  const first = chunk[0];
  if (first.startsWith(">")) return quoteBlock(chunk);
  if (/^\*\*Cross-links:\*\*/.test(first)) {
    const refs = [];
    for (const ln of chunk) {
      for (const m of ln.matchAll(/`([^`]+)`/g)) refs.push(m[1]);
    }
    return { k: "xlink", refs };
  }
  return { k: "p", t: chunk.join(" ").trim() };
}

function stripQuote(line) {
  const t = line.trim();
  return t.startsWith(">") ? t.slice(1).trim() : t;
}

function quoteBlock(chunk) {
  const lines = chunk.map(stripQuote);
  const first = lines[0] || "";
  if (first.startsWith("**Predict**")) {
    const revIdx = lines.findIndex(l => l.startsWith("**Reveal**"));
    if (revIdx < 0) return { k: "predict", q: paras(lines).join("\n\n"), a: "", broken: true };
    const qLines = lines.slice(0, revIdx);
    qLines[0] = qLines[0].replace(/^\*\*Predict\*\*\s*—\s*/, "");
    const q = paras(qLines).join("\n\n");
    const a = paras(lines.slice(revIdx).map(l => l.replace(/^\*\*Reveal\*\*\s*—\s*/, "")))
      .join("\n\n");
    return { k: "predict", q, a };
  }
  if (first.startsWith("**Reveal**")) return { k: "reveal-orphan", t: lines.join("\n") };
  if (first.startsWith("⚠")) return { k: "watch", t: lines.join(" ").replace(/^⚠\s*/, "⚠ ") };
  return { k: "note", t: lines.join("\n") };
}

/* Group a blockquote's lines into paragraphs at blank quote lines. */
function paras(lines) {
  const out = [];
  let cur = [];
  for (const l of lines) {
    if (l === "") { if (cur.length) { out.push(cur.join(" ")); cur = []; } continue; }
    cur.push(l);
  }
  if (cur.length) out.push(cur.join(" "));
  return out;
}

/* ============================ inline markdown ============================ */
/* The markdown subset: `code`, **bold**, *italic*. Everything else is
   escaped. Extension-block HTML is authored (trusted) and passes through. */
function esc(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
function inlineHTML(s) {
  const parts = s.split("`");
  let out = "";
  parts.forEach((part, i) => {
    if (i % 2 === 1) { out += "<code>" + esc(part) + "</code>"; return; }
    let t = esc(part);
    t = t.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
    t = t.replace(/\*([^*]+)\*/g, "<em>$1</em>");
    out += t;
  });
  return out;
}

