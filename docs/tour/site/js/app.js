/* ---- stepper ---- */
function rangeLabel(st) {
  return Array.isArray(st.range)
    ? "lines " + st.range[0] + "–" + st.range[1]
    : "content station — owns no lines";
}
function chipTitle(st) {
  return st.id + ". " + st.title + " — " + st.type + " · " + rangeLabel(st) +
    (st.skip ? " · skippable" : "");
}
function buildStepper() {
  const frag = document.createDocumentFragment();
  let prevLeg = null;
  ROUTE.forEach((r, idx) => {
    const st = STATION_BY_ID.get(r.id);
    if (r.leg !== prevLeg) {
      const dl = document.createElement("span");
      dl.className = "leglabel"; dl.textContent = r.leg;
      frag.appendChild(dl);
      prevLeg = r.leg;
    } else {
      const conn = document.createElement("span");
      conn.className = "conn"; conn.dataset.route = idx - 1;
      frag.appendChild(conn);
    }
    const chip = document.createElement("button");
    chip.className = "chip" + (st.skip ? " skip" : "");
    chip.dataset.id = r.id;
    chip.title = chipTitle(st);
    chip.innerHTML = "<span class=\"no\">" + st.id.replace(/^0/, "") + "</span>" +
      "<span class=\"vis\"></span>";
    frag.appendChild(chip);
  });
  trackEl.appendChild(frag);
}
