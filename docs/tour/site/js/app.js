function renderBadge() {
  const hard = checks.filter(c => !c.pass && !c.warn);
  const soft = checks.filter(c => !c.pass && c.warn);
  const pass = checks.filter(c => c.pass).length;
  if (hard.length) {
    badgeEl.textContent = "✗ content broken — " + hard.length + " failure" + (hard.length > 1 ? "s" : "");
    badgeEl.className = "fail";
    document.body.classList.add("content-fail");
  } else if (soft.length) {
    badgeEl.textContent = "✓ content ok — " + soft.length + " warning" + (soft.length > 1 ? "s" : "");
    badgeEl.className = "warn";
  } else {
    badgeEl.textContent = "✓ content ok — " + pass + " checks";
    badgeEl.className = "ok";
  }
  badgeEl.title = "click for the full self-check";
}
function renderCheckModal() {
  checkList.innerHTML = "";
  for (const c of checks) {
    const row = document.createElement("div");
    row.className = "ck " + (c.pass ? "pass" : c.warn ? "warn" : "fail");
    row.innerHTML = "<span class=\"icon\">" + (c.pass ? "✓" : c.warn ? "⚠" : "✗") + "</span>" +
      "<b>" + esc(c.name) + "</b><span class=\"det\">" + esc(c.detail) + "</span>";
    checkList.appendChild(row);
  }
  checkModal.hidden = false;
}
badgeEl.addEventListener("click", () => { renderCheckModal(); });

