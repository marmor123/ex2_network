document.addEventListener("click", e => {
  const chip = e.target.closest(".chip");
  if (chip) { openStation(chip.dataset.id, { scroll: true }); return; }
  if (e.target.closest("#startBtn")) { startTour(); return; }
  if (e.target.closest(".xchip")) {
    const sym = e.target.dataset.sym;
    const own = resolveSymbol(sym);
    if (own && own !== state.open) openStation(own, { scroll: true });
    return;
  }
  if (e.target.closest(".rev")) {
    const pred = e.target.closest(".b-pred");
    pred.querySelector(".a").classList.remove("hidden");
    e.target.style.display = "none";
    return;
  }
  const nav = e.target.closest("[data-nav]");
  if (nav && !nav.disabled) {
    const pos = state.open != null ? ROUTE_POS.get(state.open) : -1;
    const d = nav.dataset.nav === "next" ? 1 : -1;
    const npos = Math.min(ROUTE.length - 1, Math.max(0, pos + d));
    openStation(ROUTE[npos].id, { scroll: true });
    return;
  }
  if (e.target.closest("#bubbleClose")) { closeStation(); return; }
  if (e.target.closest("#cmClose") || e.target === checkModal) { checkModal.hidden = true; return; }
  /* click outside the bubble closes it */
  if (state.open && !e.target.closest("#bubble") && !e.target.closest(".fl-line") &&
      !e.target.closest("#stepper") && !e.target.closest("#selfBadge")) {
    closeStation();
  }
});
